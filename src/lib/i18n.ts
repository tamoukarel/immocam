export function traduire(lang: Lang, cle: string, vars?: Record<string, string | number>): string {
  const entree = TRADUCTIONS[cle]
  let texte = entree ? entree[lang] : cle
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      texte = texte.replaceAll(`{${k}}`, String(v))
    }
  }
  return texte
}
